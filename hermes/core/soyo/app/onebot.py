"""Bounded account-specific NapCat discovery; never returns tokens to the UI."""
from __future__ import annotations

import json
import os
from pathlib import Path
import re

from soyo.platform import is_link
from .config import read_json, update


def _files(directory):
    if not isinstance(directory, str) or not directory.strip():
        return []
    directory = Path(directory).expanduser()
    if not directory.is_absolute():
        raise ValueError('Configure an explicit absolute NapCat account directory')
    directory = Path(os.path.abspath(directory))
    if not directory.is_dir() or is_link(directory) or any(is_link(parent) for parent in directory.parents):
        return []
    return [p for p in sorted(directory.glob("onebot11_*.json"))[:128]
            if p.is_file() and not is_link(p) and p.stat().st_size <= 1024 * 1024
            and re.fullmatch(r"onebot11_[1-9][0-9]{0,19}\.json", p.name)]


def accounts(directory):
    result = []
    for file in _files(directory):
        try:
            value = json.loads(file.read_text(encoding="utf-8-sig"))
            network = value.get("network", value)
            result.append({"account_id": file.stem.removeprefix("onebot11_"),
                "http_configured": bool(network.get("httpServers")), "ws_configured": bool(network.get("websocketServers"))})
        except (ValueError, OSError):
            continue
    return result


def select(home, account_id):
    config = read_json(Path(home) / "deployment.json")
    qq = config["onebot"]
    directory = qq.get("config_directory")
    if not directory:
        raise ValueError("Configure the NapCat account config directory first")
    file = next((p for p in _files(directory) if p.stem == "onebot11_" + str(account_id)), None)
    if not file:
        raise ValueError("Account configuration was not generated by this NapCat instance")
    value = json.loads(file.read_text(encoding="utf-8-sig"))
    network = value.get("network", value)
    def listener(field, scheme):
        rows = [row for row in network.get(field, []) if row.get("enable", row.get("enabled", False)) is True]
        if len(rows) != 1:
            raise ValueError("Enable one explicit HTTP and WS listener in NapCat WebUI")
        row = rows[0]
        if str(row.get("host", "127.0.0.1")) not in {"127.0.0.1", "localhost"}:
            raise ValueError("NapCat listeners must bind loopback, not all interfaces")
        port = row.get("port")
        if not str(port).isdigit() or not 1 <= int(port) <= 65535:
            raise ValueError("NapCat listener port missing")
        token = str(row.get("token") or row.get("accessToken") or "")
        if not token:
            raise ValueError("Set NapCat's access token before selecting this account")
        return f"{scheme}://127.0.0.1:{int(port)}", token
    http, token = listener("httpServers", "http")
    ws, ws_token = listener("websocketServers", "ws")
    if token != ws_token:
        raise ValueError("HTTP and WS listener tokens must match")
    return update(home, {"onebot": {"account_id": str(account_id), "http_url": http, "ws_url": ws, "token": token}}, config["revision"])
